//  Supabase calls for the RNBA_Prod event desks. Reads and check-ins go
//  through the RPC functions in wp-sync/sql/013_app_desks.sql, so the
//  timestamps come from the server clock.
//

import Foundation
import Supabase

struct DeskService {

    private var supabase: SupabaseClient { SupabaseConfig.client }

    // MARK: - Events

    func fetchEvents() async throws -> [FestivalEvent] {
        try await supabase
            .from("Event")
            .select("eventid, name, current, date, isevening")
            .order("date")
            .order("isevening")
            .order("eventid")
            .execute()
            .value
    }

    // MARK: - Visitors

    func fetchVisitors(eventID: Int) async throws -> [EventVisitor] {
        try await supabase
            .rpc("GetEventVisitors", params: EventParams(p_eventid: eventID))
            .execute()
            .value
    }

    // MARK: - Check-ins

    /// Welcome desk: checks in (or undoes) a whole registration for one event.
    func setCheckedIn(registrationID: String, eventID: Int, checkedIn: Bool) async throws {
        try await supabase
            .rpc("CheckInRegistration", params: CheckInParams(
                p_registrationid: registrationID,
                p_eventid: eventID,
                p_checked_in: checkedIn
            ))
            .execute()
    }

    /// Food desk: marks (or undoes) one ticket's meal as served.
    func setFoodServed(visitorID: Int64, served: Bool) async throws {
        try await supabase
            .rpc("SetFoodServed", params: FoodServedParams(p_visitorid: visitorID, p_served: served))
            .execute()
    }

    // MARK: - Lookups

    func fetchVisitTypes() async throws -> [VisitTypeRow] {
        try await supabase.from("Visit_Type").select().order("visitid").execute().value
    }

    func fetchPaymentTypes() async throws -> [PaymentTypeRow] {
        try await supabase.from("Payment_Type").select("paymenttypeid, name").order("paymenttypeid").execute().value
    }

    // MARK: - Walk-in Registration

    /// Creates a contact, a registration (registrationid generated by the
    /// database, e.g. "APP-20261017-101500-9F3B"), one visitor per person
    /// for `eventID`, and optionally a payment. Returns the new
    /// registration ID.
    ///
    /// Not one transaction: if a later step fails, the earlier rows stay.
    func createWalkIn(_ walkIn: WalkInRegistration, eventID: Int, visitTypes: [VisitTypeRow]) async throws -> String {
        // Resolve every person's Visit_Type first, so nothing is written if
        // one can't be matched.
        let visitIDs = try walkIn.persons.map { person -> Int in
            let wantsFood = person.food != .none
            guard let row = visitTypes.first(where: { $0.name == person.category && $0.withfood == wantsFood }) else {
                throw DeskError.missingVisitType(category: person.category, withFood: wantsFood)
            }
            return row.visitid
        }

        let contact: ContactID = try await supabase
            .from("Contact")
            .insert(NewContact(
                telephone: walkIn.phone.nilIfBlank,
                mobile: walkIn.mobile.nilIfBlank,
                email: walkIn.email.nilIfBlank,
                address: walkIn.address.nilIfBlank
            ))
            .select("contactid")
            .single()
            .execute()
            .value

        let registration: RegistrationID = try await supabase
            .from("Registration")
            .insert(NewRegistration(
                name: walkIn.name.trimmingCharacters(in: .whitespacesAndNewlines),
                contact: contact.contactid,
                event: eventID
            ))
            .select("registrationid")
            .single()
            .execute()
            .value

        let visitors = zip(walkIn.persons, visitIDs).map { person, visitID in
            NewVisitor(
                registrationid: registration.registrationid,
                eventid: eventID,
                visitid: visitID,
                foodtypeid: person.food.foodTypeID,
                child: person.isChild,
                completed: false
            )
        }
        try await supabase.from("Visitors").insert(visitors).execute()

        if let paymentTypeID = walkIn.paymentTypeID, walkIn.paymentAmount > 0 {
            try await supabase
                .from("Payment")
                .insert(NewPayment(
                    paymenttypeid: paymentTypeID,
                    registrationid: registration.registrationid,
                    amount: walkIn.paymentAmount,
                    remarks: walkIn.paymentRemarks.nilIfBlank
                ))
                .execute()
        }

        if walkIn.checkInNow {
            try await setCheckedIn(registrationID: registration.registrationid, eventID: eventID, checkedIn: true)
        }

        return registration.registrationid
    }
}

// MARK: - Errors

nonisolated enum DeskError: LocalizedError {
    case missingVisitType(category: String, withFood: Bool)

    var errorDescription: String? {
        switch self {
        case let .missingVisitType(category, withFood):
            return "There is no visit type \"\(category)\" \(withFood ? "with" : "without") food in Visit_Type."
        }
    }
}

// MARK: - Request / Response Payloads

private nonisolated struct EventParams: Encodable, Sendable {
    let p_eventid: Int
}

private nonisolated struct CheckInParams: Encodable, Sendable {
    let p_registrationid: String
    let p_eventid: Int
    let p_checked_in: Bool
}

private nonisolated struct FoodServedParams: Encodable, Sendable {
    let p_visitorid: Int64
    let p_served: Bool
}

private nonisolated struct NewContact: Encodable, Sendable {
    let telephone: String?
    let mobile: String?
    let email: String?
    let address: String?
}

private nonisolated struct ContactID: Decodable, Sendable {
    let contactid: Int64
}

private nonisolated struct NewRegistration: Encodable, Sendable {
    let name: String
    let contact: Int64
    let event: Int
}

private nonisolated struct RegistrationID: Decodable, Sendable {
    let registrationid: String
}

private nonisolated struct NewVisitor: Encodable, Sendable {
    let registrationid: String
    let eventid: Int
    let visitid: Int
    let foodtypeid: Int?
    let child: Bool
    let completed: Bool
}

private nonisolated struct NewPayment: Encodable, Sendable {
    let paymenttypeid: Int
    let registrationid: String
    let amount: Decimal
    let remarks: String?
}

private extension String {
    var nilIfBlank: String? {
        let trimmed = trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty ? nil : trimmed
    }
}
